export function getCountryFlagUrl(isoCode: string): string {
  return `https://flagicons.lipis.dev/flags/4x3/${isoCode.toLowerCase()}.svg`;
}

export function findCountry(valueOrCode: string): CountryItem | undefined {
  if (!valueOrCode) return undefined;
  const q = valueOrCode.trim().toLowerCase();
  return WORLD_COUNTRIES.find(
    (c) =>
      c.code.toLowerCase() === q ||
      c.nameEn.toLowerCase() === q ||
      c.nameAr.toLowerCase() === q
  );
}
